export function normalizeLocale(value: string | null | undefined): Locale {
  return value === 'en' ? 'en' : 'vi';
}

export function translate(locale: Locale, key: TranslationKey): string {
  return keyedMessages[locale][key];
}

export function translateLiteral(locale: Locale, value: string): string {
  if (locale === 'en') return value;
  return viLiterals[value] ?? value;
}

export function createI18nStore(storage?: LocaleStorage) {
  let locale: Locale = 'vi';
  try { locale = normalizeLocale(storage?.getItem(LOCALE_STORAGE_KEY)); }
  catch { locale = 'vi'; }
  const listeners = new Set<() => void>();

  return {
    getLocale: () => locale,
    setLocale(next: Locale) {
      const normalized = normalizeLocale(next);
      if (normalized === locale) return;
      locale = normalized;
      try { storage?.setItem(LOCALE_STORAGE_KEY, locale); } catch { /* Persistence is best-effort. */ }
      for (const listener of listeners) listener();
    },
    subscribe(listener: () => void) {
      listeners.add(listener);
      return () => listeners.delete(listener);
    }
  };
}

